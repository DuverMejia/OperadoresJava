public class OperadoresLogicos {
    static void main(String[] args) {
    //Operadores logicos
        boolean a = true, b = false, d = false, c = true, resultado;

                //operador and
        resultado = a & b ;
        System.out.println("resultado = " + resultado);

        //operador or

        resultado = b || d ;
        System.out.println("resultado = " + resultado);

        //operador not

        resultado = !resultado;
        System.out.println("resultado = " + resultado);

    }
}
